CREATE TABLE IF NOT EXISTS servers (key TEXT PRIMARY KEY, code TEXT UNIQUE, ip TEXT, port INTEGER, name TEXT, descr TEXT, search TEXT, public INTEGER, locked INTEGER, count INTEGER, max INTEGER, rules TEXT, t INTEGER);
CREATE INDEX IF NOT EXISTS servers_t ON servers(t);
CREATE TABLE IF NOT EXISTS bans (ip TEXT PRIMARY KEY, why TEXT);
CREATE TABLE IF NOT EXISTS reports (id INTEGER PRIMARY KEY, code TEXT, why TEXT, ip TEXT, t INTEGER);
