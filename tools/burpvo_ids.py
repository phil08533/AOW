# writes src/burpvo_ids.js from the clips in dist/voice/<pack>/: which B.U.R.P. lines have a recorded clip, per voice pack
import os
root = os.path.join(os.path.dirname(__file__), '..', 'dist', 'voice')
packs = {}
if os.path.isdir(root):
    for p in sorted(os.listdir(root)):
        d = os.path.join(root, p)
        if os.path.isdir(d): packs[p] = sorted(f[:-4] for f in os.listdir(d) if f.endswith('.mp3'))
out = "// generated by tools/burpvo_ids.py: which B.U.R.P. lines have a recorded clip, per voice pack\n"
out += "const BURP_VO_PACKS = {%s};\n" % ', '.join("'%s': new Set('%s'.split(' ').filter(Boolean))" % (p, ' '.join(ids)) for p, ids in packs.items())
out += "const BURP_VO = BURP_VO_PACKS.burp || new Set();\n"
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'burpvo_ids.js'), 'w').write(out)
print(', '.join('%s: %d clips' % (p, len(i)) for p, i in packs.items()))
