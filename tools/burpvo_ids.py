# writes src/burpvo_ids.js from the clips in dist/voice/burp
import os
d = os.path.join(os.path.dirname(__file__), '..', 'dist', 'voice', 'burp')
ids = sorted(f[:-4] for f in os.listdir(d) if f.endswith('.mp3')) if os.path.isdir(d) else []
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'burpvo_ids.js'), 'w').write("// generated by tools/burpvo_ids.py: which B.U.R.P. lines have a recorded clip\nconst BURP_VO = new Set('%s'.split(' ').filter(Boolean));\n" % ' '.join(ids))
print(len(ids), 'clips')
